export type RecordType = 'violation' | 'achievement';

export type SeverityLevel = 'Ringan' | 'Sedang' | 'Berat' | 'Sangat Berat';
export type AchievementTier = 'Sekolah' | 'Kota/Kabupaten' | 'Provinsi' | 'Nasional';

export type RiskStatus =
  | 'Teladan'
  | 'Normal'
  | 'Pembinaan'
  | 'Peringatan (SP1)'
  | 'Panggilan Orang Tua (SP2)'
  | 'Kritis (SP3)';

export type ActionStatus = 'Menunggu Tindak Lanjut' | 'Sedang Dijalani' | 'Selesai Dibina';

export type SummonStatus =
  | 'Diterbitkan'
  | 'Diterima Orang Tua'
  | 'Hadir Konseling'
  | 'Dijadwalkan Ulang';

export type UserRole =
  | 'admin'
  | 'ketertiban'
  | 'guru_mapel'
  | 'bk'
  | 'wali_kelas'
  | 'orang_tua';

export interface StaffAccount {
  id: string;
  name: string;
  role: Exclude<UserRole, 'orang_tua'>;
  roleLabel: string;
  subjectOrUnit: string;
  assignedClass?: string;
}

export interface AuthUser {
  id: string;
  name: string;
  role: UserRole;
  roleLabel: string;
  assignedClass?: string;
  studentId?: string; // Scoped child ID when role === 'orang_tua'
  studentName?: string;
  studentClass?: string;
}

export interface Student {
  id: string;
  nisn: string;
  name: string;
  className: string;
  homeroomTeacher: string;
  parentName: string;
  parentPhone: string;
  parentEmail: string;
  parentAddress: string;
  parentPasswordHash?: string;
  violationPoints: number;
  achievementPoints: number;
  behaviorIndex: number;
  riskStatus: RiskStatus;
  lastUpdatedAt: string;
}

export type PublicStudent = Omit<Student, 'parentPasswordHash'>;

export interface RuleCatalogItem {
  id: string;
  code: string;
  type: RecordType;
  category: string;
  title: string;
  points: number;
  severity?: SeverityLevel;
  achievementTier?: AchievementTier;
  defaultPunishment: string;
  escalationGuidance: string;
}

export interface BehaviorRecord {
  id: string;
  studentId: string;
  ruleId: string;
  type: RecordType;
  category: string;
  title: string;
  points: number;
  severity?: SeverityLevel;
  achievementTier?: AchievementTier;
  recordedBy: string;
  recordedByRole: string;
  notes: string;
  location: string;
  occurredAt: string;
  createdAt: string;
}

export interface DisciplinaryAction {
  id: string;
  recordId: string;
  studentId: string;
  violationTitle: string;
  violationPoints: number;
  cumulativeViolationPoints: number;
  recommendedAction: string;
  sanctionLevel: string;
  assignedUnit: 'Wali Kelas' | 'Tim Ketertiban' | 'Guru BK';
  status: ActionStatus;
  evaluationNotes: string;
  dueDate: string;
  createdAt: string;
  updatedAt: string;
}

export interface NotificationItem {
  id: string;
  studentId: string;
  studentName: string;
  className: string;
  type: 'point_spike' | 'threshold_crossed' | 'achievement_milestone' | 'summon_issued';
  severity: 'info' | 'warning' | 'critical' | 'positive';
  title: string;
  message: string;
  pointDelta: number;
  recipients: string[];
  isRead: boolean;
  createdAt: string;
}

export interface SummonLetter {
  id: string;
  letterNumber: string;
  studentId: string;
  studentName: string;
  nisn: string;
  className: string;
  parentName: string;
  parentAddress: string;
  totalViolationPoints: number;
  recentViolationsSummary: string[];
  agenda: string;
  meetingDate: string;
  meetingTime: string;
  meetingLocation: string;
  counselorName: string;
  counselorNip: string;
  principalName: string;
  principalNip: string;
  status: SummonStatus;
  parentResponseNote?: string;
  issuedAt: string;
}

export interface MonthlyReportConfig {
  autoGenerateEnabled: boolean;
  autoDayOfMonth: number;
  includeParentDigest: boolean;
  schoolName: string;
  schoolAddress: string;
  schoolPhone: string;
  lastAutoGeneratedMonth: string;
}

export interface AuthConfig {
  staffPasscodeHash?: string;
}

export interface AppDatabaseState {
  staffAccounts: StaffAccount[];
  students: Student[];
  catalog: RuleCatalogItem[];
  records: BehaviorRecord[];
  disciplinaryActions: DisciplinaryAction[];
  notifications: NotificationItem[];
  summonLetters: SummonLetter[];
  monthlyConfig: MonthlyReportConfig;
  authConfig?: AuthConfig;
}

export interface ClientAppState {
  staffAccounts: StaffAccount[];
  students: PublicStudent[];
  catalog: RuleCatalogItem[];
  records: BehaviorRecord[];
  disciplinaryActions: DisciplinaryAction[];
  notifications: NotificationItem[];
  summonLetters: SummonLetter[];
  monthlyConfig: MonthlyReportConfig;
}
